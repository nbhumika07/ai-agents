# --------------------------------
# Function to create timetable
# --------------------------------

def create_timetable(topics, days):

    timetable = {}

    if days < 2:
        timetable[1] = [
            "Study all topics",
            "Quick Revision"
        ]
        return timetable

    # Reserve the last day for revision
    study_days = days - 1

    # Divide topics across study days
    base_topics = len(topics) // study_days
    extra_topics = len(topics) % study_days

    topic_index = 0

    # Keep track of topics already studied
    studied_topics = []

    for day in range(1, days + 1):

        timetable[day] = []

        # Last day = Revision Day
        if day == days:

            timetable[day].append(
                "Full Revision - All Topics"
            )

            timetable[day].append(
                "Practice Questions / Mock Test"
            )

            continue

        # Determine today's topics
        number_of_topics = base_topics

        if day <= extra_topics:
            number_of_topics += 1

        today_topics = []

        for i in range(number_of_topics):

            if topic_index < len(topics):

                topic = topics[topic_index]

                today_topics.append(topic)
                studied_topics.append(topic)

                topic_index += 1

        # Add today's topics
        for topic in today_topics:
            timetable[day].append(
                "Study: " + topic
            )

        # Add revision every second day
        if day % 2 == 0:

            previous_topics = studied_topics[:-len(today_topics)]

            if previous_topics:

                timetable[day].append(
                    "Revision: " +
                    ", ".join(previous_topics)
                )

    return timetable


